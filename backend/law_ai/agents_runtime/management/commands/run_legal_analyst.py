"""``run_legal_analyst`` — run the LegalAnalyst agent live.

Produces an IRAC analysis end-to-end. When the dev-time Claude Code provider is
opted in (``LSAT_LLM_PROVIDER=claude_code`` + token, in development) the analysis
is generated by Claude Code over OAuth; otherwise the static mock is returned.

    make legal-analyst-demo
    make legal-analyst-demo ARGS='--question "Is a clickwrap agreement enforceable?"'
"""

from __future__ import annotations

from typing import Any

from asgiref.sync import async_to_sync
from django.core.management.base import BaseCommand

from law_ai.core import claude_code

_DEFAULT_QUESTION = (
    "A retailer's website shows a 'Sign up' button with the terms of service "
    "linked in small text beside it; the user clicks through without opening the "
    "terms. Is the resulting clickwrap arbitration clause enforceable?"
)


class Command(BaseCommand):
    help = "Run the LegalAnalyst agent once and print the IRAC analysis."

    def add_arguments(self, parser: Any) -> None:
        parser.add_argument("--question", default=_DEFAULT_QUESTION)
        parser.add_argument("--facts", default="")
        parser.add_argument("--jurisdiction", default="U.S. federal")

    def handle(self, *args: Any, **opts: Any) -> None:
        from law_ai.agents_runtime.crews.legal_analyst import LegalAnalyst

        self._print_gate()

        self.stdout.write(self.style.MIGRATE_HEADING("\nRunning LegalAnalyst (IRAC)…"))
        self.stdout.write(f"  question: {opts['question']}")

        agent = LegalAnalyst()
        out = async_to_sync(agent.run)(
            {
                "question": opts["question"],
                "facts": opts["facts"],
                "jurisdiction": opts["jurisdiction"],
            }
        )

        ran_on_claude = out.trace_id is not None and claude_code.is_active()
        banner = (
            self.style.SUCCESS("via Claude Code")
            if ran_on_claude and out.confidence > 0
            else self.style.WARNING("via mock / fallback")
        )
        self.stdout.write(f"\nResult ({banner}):")
        self.stdout.write(f"  confidence : {out.confidence}")
        self.stdout.write(f"  trace_id   : {out.trace_id}")
        self.stdout.write(self.style.MIGRATE_HEADING("\nIRAC"))
        self.stdout.write(f"  Issue       : {out.issue}")
        self.stdout.write(f"  Rule        : {out.rule}")
        self.stdout.write(f"  Application : {out.application}")
        self.stdout.write(f"  Conclusion  : {out.conclusion}")
        if out.sources:
            authorities = ", ".join(s.get("title", "?") for s in out.sources)
            self.stdout.write(f"  Authorities : {authorities}")
        if out.reasoning_trace:
            self.stdout.write(f"  Notes       : {' | '.join(out.reasoning_trace)}")

        if ran_on_claude and out.confidence > 0:
            self.stdout.write(
                self.style.SUCCESS(
                    "\nLive LegalAnalyst run via Claude Code completed "
                    "(provenance logged; authorities require verification)."
                )
            )

    def _print_gate(self) -> None:
        self.stdout.write(self.style.MIGRATE_HEADING("Claude Code OAuth gate"))
        rows = {
            "development env": claude_code.is_development(),
            "oauth token": claude_code.oauth_token() is not None,
            "api key (tier 2)": claude_code.api_key() is not None,
            "model": claude_code.model(),
        }
        for key, value in rows.items():
            self.stdout.write(f"  {key:<18}: {value}")
        reason = claude_code.inactive_reason()
        if reason:
            self.stdout.write(self.style.WARNING(f"  (inactive: {reason})"))
