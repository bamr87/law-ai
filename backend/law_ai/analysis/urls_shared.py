"""Public share-link resolution (BL-20260429-26 / spec 036 T-007).

``GET /api/shared/<slug>`` is the one deliberately unauthenticated route in
the API: the slug *is* the credential, which is why minted slugs carry 32
random bytes and why revocation is immediate and permanent.

Three guards make an unauthenticated read defensible:

* the run's owner had to be signed in to mint the slug at all;
* a revoked slug, an archived run and a run marked ``shareable=False`` are all
  a flat 404 — indistinguishable from a slug that never existed, so probing
  learns nothing;
* the payload always carries the not-legal-advice disclaimer, because a
  reader who arrives from a link has none of the context the Studio gives.
"""

from __future__ import annotations

from typing import Any

from django.urls import path
from rest_framework import status
from rest_framework.permissions import AllowAny
from rest_framework.response import Response
from rest_framework.views import APIView

from law_ai.core.provenance import provenance

DISCLAIMER = (
    "Not legal advice. This analysis was generated by an AI system and may be "
    "incomplete or wrong. Consult a licensed attorney in your jurisdiction."
)


class SharedAnalysisView(APIView):
    """Resolve a share slug to the analysis it bookmarks. Read-only."""

    permission_classes = [AllowAny]
    authentication_classes: list[Any] = []

    def get(self, request: Any, slug: str, *args: Any, **kwargs: Any) -> Any:
        from law_ai.analysis.models import ShareLink

        link = (
            ShareLink.objects.select_related("analysis")
            .filter(
                slug=slug,
                revoked_at__isnull=True,
                analysis__archived_at__isnull=True,
                analysis__shareable=True,
            )
            .first()
        )
        if link is None:
            return Response(
                {"detail": "share link not found"},
                status=status.HTTP_404_NOT_FOUND,
            )
        provenance.log_event(
            "share_link.viewed",
            {
                "source": "analysis",
                "analysis_id": link.analysis_id,
                "slug": slug,
            },
        )
        payload = link.analysis.as_payload()
        payload["shared"] = True
        payload["slug"] = slug
        payload["label"] = link.label
        payload["disclaimer"] = DISCLAIMER
        return Response(payload)


urlpatterns = [
    path("<str:slug>", SharedAnalysisView.as_view(), name="shared-analysis"),
]
