LABELS: tuple[ChoiceLabel, ...] = ("A", "B", "C", "D", "E")

#: Spelled out, because "5 applicants are heard on 5 consecutive days" reads as
#: generated text and "Five applicants" reads as an exam.
_COUNT_WORDS = {
    2: "Two",
    3: "Three",
    4: "Four",
    5: "Five",
    6: "Six",
    7: "Seven",
    8: "Eight",
    9: "Nine",
}


def _count(n: int) -> str:
    return _COUNT_WORDS.get(n, str(n))


class SynthError(RuntimeError):
    """Generation produced something that did not verify."""


class Provenance(BaseModel):
    """Everything needed to regenerate this exact item."""

    engine_version: str = ENGINE_VERSION
    schema_id: str
    schema_version: int
    domain_id: str
    seed: int
    proof_kind: str
    #: The premise arrangement the schema drew — chain length, trigger
    #: position, rule count, menu ids — so an auditor can see the item's shape
    #: without re-running the draw. Empty for a fixed-arrangement schema.
    arrangement: dict[str, int | str] = Field(default_factory=dict)
    #: The band the schema declares, kept beside the measured one so a
    #: disagreement stays visible after the item ships (BL-20260903-14).
    declared_difficulty: str = ""
    #: The structural difficulty proxy (an ``ItemComplexity`` dump) the emitted
    #: band was measured from. ``None`` on a structural item, which has no
    #: model space to measure and keeps its declared band.
    complexity: dict[str, Any] | None = None
    #: The polish round's yield (a ``PolishYield`` dump), when ``--polish`` was
    #: asked for — proposed, accepted, rejects by reason, and the provider tier
    #: that answered. ``None`` on an unpolished item.
    polish: dict[str, Any] | None = None


@dataclass(frozen=True)
class SynthItem:
    question: Question
    guide: SolveGuide
    report: VerificationReport
    provenance: Provenance

    @property
    def ok(self) -> bool:
        return self.report.ok


def _item_id(schema_id: str, domain_id: str, seed: int, section: str) -> str:
    """A stable, collision-resistant id that cannot be mistaken for a bank id.

    The ``syn-`` prefix matters: a synthesized item and a hand-authored one look
    identical downstream, and the id is the one place the difference stays
    visible without consulting provenance.
    """
    digest = hashlib.sha256(
        f"{ENGINE_VERSION}|{schema_id}|{domain_id}|{seed}".encode()
    ).hexdigest()[:8]
    return f"syn-{section.lower()}-{digest}"


def _render_choice(choice: FormalChoice, binding: Binding, family: str) -> str:
    if choice.surface is not None:
        return choice.surface
    if choice.statement is None:  # pragma: no cover - schemas always supply one
        raise SynthError("choice has neither a statement nor surface text")
    if family == "acceptability":
        return render_arrangement(choice.statement, binding)
    return render_statement(choice.statement, binding)


def _question(
    blueprint: Blueprint, binding: Binding, schema: Schema, rng: random.Random
) -> str:
    """The question sentence, with any local supposition folded into it.

    A local games question states its supposition in the question — "If the
    audit is heard third, which one of the following must be true?" — because
    it holds for that question alone. The supposition is still a premise for
    the proof; this only decides where the reader meets it.
    """
    sentence = schema.stem(rng)
    if blueprint.local_condition is None:
        return sentence
    condition = decapitalize(
        render_statement(blueprint.local_condition, binding).rstrip("."), binding
    )
    return f"If {condition}, {sentence[0].lower()}{sentence[1:]}"


def _stimulus(
    blueprint: Blueprint, binding: Binding, schema: Schema, *, noun: str
) -> str:
    parts: list[str] = list(blueprint.preamble)
    # Every game needs its board described before its rules, whatever the
    # question family is: an ordering item and a "cannot be true" item over the
    # same rules share a setup sentence.
    if binding.ordering is not None:
        entities = ", ".join(binding.entities[k] for k in sorted(binding.entities))
        parts.append(
            f"{_count(len(binding.entities))} {noun} — {entities} — are taken up "
            f"{binding.ordering.frame.format(n=_count(len(binding.entities)).lower())}."
        )
    elif binding.group_set is not None:
        entities = ", ".join(binding.entities[k] for k in sorted(binding.entities))
        names = [binding.groups[k] for k in sorted(binding.groups)]
        groups = (
            " and ".join(names)
            if len(names) == 2
            else ", ".join(names[:-1]) + f", and {names[-1]}"
        )
        parts.append(
            f"{_count(len(binding.entities))} {noun} — {entities} — are each "
            f"placed in one of {_count(len(names)).lower()} "
            f"{binding.group_set.unit}s: {groups}."
        )
    # The local supposition belongs to the question, not the board.
    parts.extend(
        render_statement(p, binding)
        for p in blueprint.premises
        if p is not blueprint.local_condition
    )
    if blueprint.conclusion is not None:
        parts.append(
            "It follows that "
            + render_statement(blueprint.conclusion, binding)[0].lower()
            + render_statement(blueprint.conclusion, binding)[1:]
        )
    return " ".join(parts)


def _build_guide(
    *,
    question_id: str,
    blueprint: Blueprint,
    binding: Binding,
    schema: Schema,
    credited_label: str,
    credited_text: str,
) -> SolveGuide:
    """A walkthrough assembled from what the checker actually did."""
    steps: list[SolveStep] = [
        SolveStep(
            kind="orient",
            title="Name the task",
            text=schema.method(),
        )
    ]

    if blueprint.premises:
        rules = [
            NotationRule(
                rule_text=render_statement(p, binding), symbols=symbolize(p, binding)
            )
            for p in blueprint.premises
        ]
        if blueprint.conclusion is not None:
            # On an assumption item the gap between the premises and the
            # conclusion *is* the question, so a board showing only the
            # premises hides the one thing the learner needs to see.
            rules.append(
                NotationRule(
                    rule_text=render_statement(blueprint.conclusion, binding),
                    symbols=symbolize(blueprint.conclusion, binding),
                    note="the conclusion — what the premises must be made to reach",
                )
            )
        note = "; ".join(legend(binding)) or None
        steps.append(
            SolveStep(
                kind="symbolize",
                title="Put the statements into notation",
                text=(
                    "Translate each statement before doing anything with it. "
                    + (f"Legend — {note}." if note else "")
                ).strip(),
                representation=NotationRep(rules=rules),
            )
        )

    steps.append(
        SolveStep(
            kind="infer",
            title="Combine what the statements force",
            text=(
                "Work out what holds in every case the statements allow, then "
                "test the choices against that rather than against your sense of "
                "what sounds right. Four of them will be consistent with the "
                "statements without following from them."
            ),
        )
    )
    steps.append(
        SolveStep(
            kind="answer",
            title="The credited answer",
            text=f"The answer is {credited_label}. {credited_text}",
            spoiler=True,
        )
    )
    return SolveGuide(
        question_id=question_id,
        method=schema.method(),
        steps=steps,
        source=f"synthesized ({ENGINE_VERSION}, {schema.meta.id})",
    )


def generate(
    schema_id: str,
    domain_id: str,
    *,
    seed: int,
    domain_override: DomainPack | None = None,
) -> SynthItem:
    """Build one item and prove it. Raises if it does not verify.

    ``domain_override`` swaps in an in-memory pack — the polish path uses it to
    re-render over an extended vocabulary without touching the loader cache.
    The schema, the seed and the templates are unchanged, so the blueprint and
    every entailment are identical; only the words differ.
    """
    schema = get_schema(schema_id)
    domain = domain_override if domain_override is not None else get_domain(domain_id)
    if not domain.supports(schema.meta.capability):
        raise SchemaError(
            f"domain {domain_id!r} cannot supply {schema.meta.capability!r} "
            f"content for schema {schema_id!r}"
        )

    # Two generators, deliberately. The skeleton — chain length, trigger
    # position, rule set, distractor draw — is keyed on the schema and seed
    # alone, so the same seed yields the *same proof* in every domain and the
    # spec's claim that a domain swap changes words and nothing else holds
    # literally. The words themselves are keyed on the domain as well.
    skeleton_rng = random.Random(f"{ENGINE_VERSION}|{schema_id}|{seed}")
    rng = random.Random(f"{ENGINE_VERSION}|{schema_id}|{domain_id}|{seed}")
    blueprint = schema.build(skeleton_rng, domain)
    spec = blueprint.binding_spec
    binding = bind(
        domain,
        rng,
        property_slots=spec.property_slots,
        entity_slots=spec.entity_slots,
        group_slots=spec.group_slots,
        needs_ordering=spec.needs_ordering,
    )

    # The credited choice is built first and shuffled into position, so key
    # placement carries no signal — a generator that always keyed A would be
    # trivially gameable.
    ordered = list(blueprint.choices)
    rng.shuffle(ordered)
    labelled = [
        LabelledChoice(
            label=LABELS[i],
            role=choice.role,
            text=_render_choice(choice, binding, blueprint.family),
            statement=choice.statement,
        )
        for i, choice in enumerate(ordered)
    ]
    if len(labelled) != CHOICE_COUNT:
        raise SynthError(
            f"{schema_id} produced {len(labelled)} choices, expected {CHOICE_COUNT}"
        )

    report = verify(blueprint, labelled, schema_id=schema_id)
    if not report.ok:
        raise SynthError(
            f"{schema_id}/{domain_id}/seed={seed} failed verification: "
            + "; ".join(f"{c.name}: {c.detail}" for c in report.failures)
        )

    credited = next(c for c in labelled if c.role.startswith("credited"))
    question_id = _item_id(schema_id, domain_id, seed, schema.meta.section)
    # The band is measured from the item's own structure and only then clamped
    # to the schema's declared judgement (BL-20260903-14): the arrangement is
    # drawn per seed, so two items from one schema are not equally hard and
    # must not claim to be.
    complexity = measure_complexity(blueprint, report)
    difficulty = blend_difficulty(schema.meta.difficulty, complexity)
    question = Question(
        id=question_id,
        section=schema.meta.section,
        type=schema.meta.section,
        difficulty=difficulty,
        stem=(
            f"{_stimulus(blueprint, binding, schema, noun=domain.entity_noun)}\n\n"
            f"{_question(blueprint, binding, schema, rng)}"
        ),
        choices=[Choice(label=c.label, text=c.text) for c in labelled],
        correct=credited.label,
        explanation=schema.explain(blueprint, binding, credited.text),
        source=f"synthesized ({ENGINE_VERSION}, {schema_id}, {domain_id})",
        concepts=list(schema.meta.concepts),
    )

    guide = _build_guide(
        question_id=question_id,
        blueprint=blueprint,
        binding=binding,
        schema=schema,
        credited_label=credited.label,
        credited_text=credited.text,
    )
    problems = validate_guide_quality(guide, question)
    if problems:
        raise SynthError(
            f"{schema_id}/{domain_id}/seed={seed} produced an invalid guide: "
            + "; ".join(problems)
        )

    return SynthItem(
        question=question,
        guide=guide,
        report=report,
        provenance=Provenance(
            schema_id=schema_id,
            schema_version=schema.meta.version,
            domain_id=domain_id,
            seed=seed,
            proof_kind=schema.meta.proof_kind,
            arrangement=dict(blueprint.arrangement),
            declared_difficulty=schema.meta.difficulty,
            complexity=complexity.dump() if complexity is not None else None,
        ),
    )


def generate_batch(
    schema_id: str, domain_id: str, *, count: int, start_seed: int = 0
) -> list[SynthItem]:
    """``count`` items from consecutive seeds, de-duplicated by question id."""
    items: list[SynthItem] = []
    seen: set[str] = set()
    seed = start_seed
    # Different seeds can land on the same skeleton and binding; skip the repeat
    # rather than shipping two items that read identically.
    attempts = 0
    while len(items) < count and attempts < count * 20:
        attempts += 1
        item = generate(schema_id, domain_id, seed=seed)
        seed += 1
        if item.question.id in seen:
            continue
        seen.add(item.question.id)
        items.append(item)
    if len(items) < count:  # pragma: no cover - defensive
        raise SynthError(
            f"{schema_id}/{domain_id}: produced {len(items)} distinct items, wanted {count}"
        )
    return items


class SweepFailure(BaseModel):
    schema_id: str
    domain_id: str
    seed: int
    error: str


class SweepResult(BaseModel):
    generated: int = 0
    combinations: int = 0
    failures: list[SweepFailure] = Field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.failures


def sweep(*, seeds: int = 5) -> SweepResult:
    """Generate across every schema x domain x ``seeds`` and report every failure.

    The engine's own regression test: a schema that stops verifying, a domain
    pack that stops supplying what a schema needs, or a realizer change that
    breaks a guide all surface here rather than in the bank.
    """
    result = SweepResult()
    for schema in all_schemas():
        for domain in load_domains().values():
            if not domain.supports(schema.meta.capability):
                continue
            result.combinations += 1
            for seed in range(seeds):
                try:
                    generate(schema.meta.id, domain.id, seed=seed)
                    result.generated += 1
                except Exception as exc:
                    result.failures.append(
                        SweepFailure(
                            schema_id=schema.meta.id,
                            domain_id=domain.id,
                            seed=seed,
                            error=str(exc),
                        )
                    )
    return result


def as_draft(item: SynthItem) -> dict[str, Any]:
    """One item in the shape the spec 024 intake gates expect."""
    payload = item.question.model_dump(mode="json")
    payload["synth"] = item.provenance.model_dump(mode="json")
    return payload
