"""``manage.py export_api_schema`` — publish the API's Pydantic contracts.

The frontend's request/response types are hand-written TypeScript interfaces in
``frontend/lib/api.ts``; the backend's are Pydantic models. Nothing used to
connect the two, so a renamed or newly-required field on the server drifted
silently until a user hit it (BL-20260811-16).

This command dumps ``model_json_schema()`` for the contracts the browser
actually depends on into ``frontend/__tests__/fixtures/api-schema.json``. Two
gates consume it:

* ``frontend/__tests__/lib/apiContract.test.ts`` compares each schema against
  the matching TS interface — a required backend field the client never
  declares, or a client field the server does not send, fails ``make test``.
* ``backend/tests/core/test_export_api_schema.py`` regenerates the fixture and
  fails when the checked-in copy is stale, so a model change cannot land
  without refreshing it.

Regenerate with::

    make manage CMD=export_api_schema

``--check`` exits 1 instead of writing when the fixture is out of date, and
``--print`` writes the document to stdout without touching the tree.
"""

from __future__ import annotations

import json
from argparse import ArgumentParser
from pathlib import Path
from typing import Any

from django.conf import settings
from django.core.management.base import BaseCommand, CommandError
from pydantic import BaseModel

# Repo-relative destination. Kept next to the frontend fixtures it feeds so a
# reviewer sees the contract change in the same diff as the client change.
FIXTURE_RELPATH = Path("frontend/__tests__/fixtures/api-schema.json")


def _contracts() -> dict[str, type[BaseModel]]:
    """The Pydantic models the browser sends or receives, by contract name.

    Names match the TypeScript interface in ``frontend/lib/api.ts`` that the
    client uses for the same payload; ``apiContract.test.ts`` pairs them by
    that name, so a rename on either side must be made on both.
    """
    from law_ai.agents_runtime.crews.legal_analyst import IRACOutput
    from law_ai.agents_runtime.crews.precedent_hunter import PrecedentList
    from law_ai.analysis.urls import AnalysisRequest, AnalysisResponse
    from law_ai.lsat.services.bank import PublicQuestion
    from law_ai.lsat.services.tutor import TutorRequest, TutorResponse
    from law_ai.lsat.urls import GradeRequest, GradeResponse

    return {
        "AnalysisRequest": AnalysisRequest,
        "AnalysisResponse": AnalysisResponse,
        "IRACOutput": IRACOutput,
        "PrecedentList": PrecedentList,
        "LsatQuestion": PublicQuestion,
        "LsatGradeRequest": GradeRequest,
        "LsatGradeResponse": GradeResponse,
        "LsatTutorRequest": TutorRequest,
        "LsatTutorResponse": TutorResponse,
    }


def build_document() -> dict[str, Any]:
    """Return the full schema document (stable ordering, JSON-ready)."""
    return {
        "$comment": (
            "Generated by `manage.py export_api_schema` — do not hand-edit. "
            "Regenerate with `make manage CMD=export_api_schema`."
        ),
        "contracts": {
            name: model.model_json_schema()
            for name, model in sorted(_contracts().items())
        },
    }


def serialise(document: dict[str, Any]) -> str:
    """Deterministic on-disk form: sorted keys, two-space indent, trailing NL."""
    return json.dumps(document, indent=2, sort_keys=True) + "\n"


def fixture_path() -> Path:
    """Absolute path to the checked-in fixture.

    ``settings.REPO_ROOT`` already resolves the container case (``/repo``, via
    the compose env var) and the host case (one level above ``backend/``).
    """
    return Path(settings.REPO_ROOT) / FIXTURE_RELPATH


class Command(BaseCommand):
    help = "Export the browser-facing Pydantic contracts as JSON Schema."

    def add_arguments(self, parser: ArgumentParser) -> None:
        parser.add_argument(
            "--check",
            action="store_true",
            help="Exit non-zero when the checked-in fixture is stale.",
        )
        parser.add_argument(
            # NOT "--stdout": Django's ``call_command`` already reserves that
            # option name for the output stream, so the flag would always look
            # set when a test passes ``stdout=``.
            "--print",
            dest="print_only",
            action="store_true",
            help="Print the document instead of writing the fixture.",
        )

    def handle(self, *args: object, **options: object) -> None:
        payload = serialise(build_document())

        if options.get("print_only"):
            self.stdout.write(payload)
            return

        target = fixture_path()
        current = target.read_text(encoding="utf-8") if target.is_file() else None

        if options.get("check"):
            if current != payload:
                raise CommandError(
                    f"{FIXTURE_RELPATH} is stale — run "
                    "`make manage CMD=export_api_schema`"
                )
            self.stdout.write(self.style.SUCCESS(f"{FIXTURE_RELPATH} is current"))
            return

        if current == payload:
            self.stdout.write(f"{FIXTURE_RELPATH} unchanged")
            return

        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(payload, encoding="utf-8")
        self.stdout.write(self.style.SUCCESS(f"wrote {FIXTURE_RELPATH}"))
