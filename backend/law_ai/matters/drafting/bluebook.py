"""Bluebook citation forms (BL-20260817-03, first half).

Citation formatting is a professional-liability surface, which decides the
shape of this module: it is **pure and deterministic** — dicts in, strings
out, no model, no network, no database — so every form it produces can be
unit-tested against a fixture and reviewed by a human who knows the rules.
Nothing here is generated by an LLM, and nothing here invents a field: a
missing reporter or year is *omitted*, never guessed, because a plausible
wrong citation is worse than an obviously incomplete one.

Coverage is deliberately narrow and honest about it — the three forms the
knowledge graph actually carries metadata for:

* **Cases** (Rule 10): ``Marbury v. Madison, 5 U.S. 137 (1803)``
* **Statutes** (Rule 12): ``42 U.S.C. § 1983 (2018)``
* **Regulations** (Rule 14): ``29 C.F.R. § 1630.2 (2024)``

Short forms (``id.``, supra) and pin cites beyond a simple page are **not**
implemented; a caller asking for one gets the full form back rather than a
guess. The renderers that would turn this into DOCX/PDF (the rest of the
item) need runtime dependencies this image does not carry yet.
"""

from __future__ import annotations

from typing import Any

#: What a citation renders as when the record carries nothing usable.
UNKNOWN = "(citation unavailable)"


def _clean(value: Any) -> str:
    return str(value or "").strip()


def _year(value: Any) -> str:
    """Year from an ISO date, a bare year, or nothing."""
    text = _clean(value)
    if len(text) >= 4 and text[:4].isdigit():
        return text[:4]
    return ""


def case_citation(record: dict[str, Any]) -> str:
    """Rule 10: ``<Case Name>, <vol> <reporter> <page> (<court> <year>)``.

    The court parenthetical is dropped for the U.S. Supreme Court, per Rule
    10.4(a) — ``(1803)``, not ``(U.S. 1803)``.
    """
    name = _clean(record.get("title") or record.get("case_name"))
    volume = _clean(record.get("reporter_volume"))
    reporter = _clean(record.get("reporter"))
    page = _clean(record.get("reporter_page"))
    year = _year(record.get("decided_at") or record.get("year"))
    court = _clean(record.get("court_abbrev") or record.get("court"))
    if court.lower() in {"us-supreme", "scotus", "u.s. supreme court", "us"}:
        court = ""

    if not name:
        return UNKNOWN
    parts = [name]
    reporter_span = " ".join(p for p in (volume, reporter, page) if p)
    if reporter_span:
        parts.append(reporter_span)
    body = ", ".join(parts)
    parenthetical = " ".join(p for p in (court, year) if p)
    if parenthetical:
        return f"{body} ({parenthetical})"
    return body


def statute_citation(record: dict[str, Any]) -> str:
    """Rule 12: ``<title> <code> § <section> (<year>)``."""
    title = _clean(record.get("title_number") or record.get("code_title"))
    code = _clean(record.get("code") or record.get("code_abbrev"))
    section = _clean(record.get("section") or record.get("section_number"))
    year = _year(record.get("effective_at") or record.get("year"))

    if not code and not section:
        # A pre-formatted citation string is the graph's other shape.
        stored = _clean(record.get("citation"))
        return stored or UNKNOWN
    head = " ".join(p for p in (title, code) if p)
    body = f"{head} § {section}".strip() if section else head
    return f"{body} ({year})" if year else body


def regulation_citation(record: dict[str, Any]) -> str:
    """Rule 14: ``<title> C.F.R. § <section> (<year>)``."""
    enriched = dict(record)
    enriched.setdefault("code", "C.F.R.")
    return statute_citation(enriched)


#: Node label → formatter. Anything else falls back to whatever citation
#: string the record already carries, so an unmodelled kind degrades to the
#: source's own wording rather than to a fabricated form.
FORMATTERS = {
    "Case": case_citation,
    "Statute": statute_citation,
    "StatuteSection": statute_citation,
    "Regulation": regulation_citation,
}


def format_citation(record: dict[str, Any], *, label: str = "") -> str:
    """Format one authority by its node label."""
    kind = label or _clean(record.get("node_label") or record.get("type"))
    formatter = FORMATTERS.get(kind)
    if formatter is None:
        return _clean(record.get("citation")) or UNKNOWN
    return formatter(record)


def format_table(records: list[dict[str, Any]]) -> list[str]:
    """A table of authorities: unique, alphabetised, stable."""
    seen = {format_citation(r) for r in records}
    seen.discard(UNKNOWN)
    return sorted(seen)


__all__ = [
    "FORMATTERS",
    "UNKNOWN",
    "case_citation",
    "format_citation",
    "format_table",
    "regulation_citation",
    "statute_citation",
]
