"""Generated reference pages must match their sources (UPS-DOC-05).

``docs/reference/`` holds reference that is derived, not written:

- ``make-targets.md`` — ``scripts/gen_make_reference.py`` renders ``make help``,
  the comment above each target and the ``.vscode/tasks.json`` labels;
- ``http-routes.md`` — ``scripts/gen_route_reference.py`` reads the Django
  URLconf statically (no Django import);
- ``docs/README.md`` — the vendored ``tools/docs_index.py`` builds the docs
  index from every document's summary line.

AGENTS.md, README.md and the guides link these pages instead of restating a
command or route table, so a stale page is the one place drift would hide.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

from tests.conftest import run_subprocess

pytestmark = pytest.mark.smoke

GENERATORS = {
    "docs/reference/make-targets.md": "scripts/gen_make_reference.py",
    "docs/reference/http-routes.md": "scripts/gen_route_reference.py",
}


@pytest.mark.parametrize("page,script", sorted(GENERATORS.items()))
def test_generated_reference_is_current(
    repo_root: Path, page: str, script: str
) -> None:
    result = run_subprocess([sys.executable, script, "--check"], cwd=repo_root)
    assert result.returncode == 0, (
        f"{page} is stale (or its source failed to parse) — run "
        f"`python3 {script}`:\n{result.stdout}{result.stderr}"
    )
    text = (repo_root / page).read_text(encoding="utf-8")
    assert text.startswith(
        f"<!-- GENERATED by python3 {script}"
    ), f"{page} must open with the GENERATED marker naming its command"


def test_docs_index_is_current_and_every_doc_has_a_summary(repo_root: Path) -> None:
    """`docs/README.md` is the generated docs index (UPS-DOC-02/03).

    `tools/docs_index.py` (vendored from the hub, never edited here) builds
    the index span from each document's `>` summary line, so a new doc with no
    summary, or one added without `--write`, fails here rather than drifting.
    """
    for mode in ("--lint", "--check"):
        result = run_subprocess(
            [sys.executable, "tools/docs_index.py", mode], cwd=repo_root
        )
        assert result.returncode == 0, (
            f"tools/docs_index.py {mode} failed — add a `> summary` line under the "
            "document's H1, then run `python3 tools/docs_index.py --write`:\n"
            + result.stdout
            + result.stderr
        )
