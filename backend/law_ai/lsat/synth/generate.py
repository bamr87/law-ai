"""The generator — schema + domain + seed → a verified, teachable item.

Spec 049 FR-8/FR-12, NFR-DETERMINISM-1, NFR-PERF-1, NFR-AUDIT-1.

Three properties this module is responsible for:

**Determinism.** ``(schema, domain, seed)`` fully determines the output. Every
random draw comes from one seeded generator, so an item in the bank can be
regenerated byte-for-byte from its provenance — which is what makes a synthetic
item auditable at all.

**Proof before emission.** Nothing is returned until :mod:`~law_ai.lsat.synth.verify`
has run. An item that fails a check raises rather than being emitted with a
warning; a generator that can emit unverified content is a generator nobody can
trust the output of.

**Teachability.** Every item ships with a solve guide *derived from the proof* —
the symbolization the checker used, the inference it found, the answer. Guide
coverage has fallen every time the bank grew (BL-20260901-04); here it cannot,
because the guide is a by-product of the same work.
"""

